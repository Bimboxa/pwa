import { useEffect, useRef } from "react";

import { useDispatch, useSelector } from "react-redux";
import { useLiveQuery } from "dexie-react-hooks";

import { triggerAnnotationsUpdate } from "Features/annotations/annotationsSlice";

import db from "App/db/db";
import useReadOnlyScope from "Features/scopes/hooks/useReadOnlyScope";

import applyPathArrayService from "../services/applyPathArrayService";
import deletePathArrayChildrenService from "../services/deletePathArrayChildrenService";
import getPathArraySignature, {
  hasPathArray,
} from "../utils/getPathArraySignature";

// Changes of the sources coalesce this long (a vertex drag = one pass).
const DEBOUNCE_MS = 400;

const isLive = (row) => Boolean(row) && !row.deletedAt;

/**
 * Keeps the annotations generated by a path array (« Calepinage » of a
 * POLYLINE — `annotation.pathArray`, applyPathArrayService) in sync with
 * their source, project-wide:
 *
 *   - source edited (vertices, arcs, closure, altitude), settings edited
 *     (step, template), template or base map scale edited: the children are
 *     REGENERATED (reconciled in place);
 *   - a child is missing / in excess: same;
 *   - source deleted, or its path array removed: the children are DELETED.
 *
 * Change detection: `pathArray.appliedSignature` / `appliedCount` (what the
 * children were generated from) vs the current signature
 * (getPathArraySignature) and the live children count.
 *
 * A watcher rather than a call at every commit site: every edit path (2D
 * drags, commands, 3D edits, assistant batches, undo / redo) ends in Dexie
 * writes this observes. Its writes push NO undo entry (tx.skipUndo): undoing
 * the source change re-derives the children. The deletion of a source also
 * cascades in useDeleteAnnotations (same undo group, so Ctrl+Z brings the
 * children back with it) — this watcher is the backstop for the other paths.
 *
 * Skipped in read-only scopes; a source whose regeneration fails is left
 * alone until it changes again.
 */
export default function usePathArraySync() {
  // data

  const dispatch = useDispatch();
  const projectId = useSelector((s) => s.projects.selectedProjectId);
  const scopeId = useSelector((s) => s.scopes.selectedScopeId);
  const { isReadOnly } = useReadOnlyScope();

  // Sources of the project (annotations carrying a path array) and the
  // children count of every referenced source — live or not.
  const state = useLiveQuery(async () => {
    if (!projectId) return { sources: [], childCounts: {} };
    const rows = await db.annotations
      .where("projectId")
      .equals(projectId)
      .toArray();
    const sources = [];
    const childCounts = {};
    for (const a of rows) {
      if (!isLive(a)) continue;
      if (a.pathArraySourceAnnotationId) {
        childCounts[a.pathArraySourceAnnotationId] =
          (childCounts[a.pathArraySourceAnnotationId] ?? 0) + 1;
      }
      if (hasPathArray(a)) {
        sources.push({
          id: a.id,
          appliedSignature: a.pathArray.appliedSignature ?? null,
          appliedCount: a.pathArray.appliedCount ?? null,
        });
      }
    }
    return { sources, childCounts };
  }, [projectId]);

  const sourceIdsKey = (state?.sources ?? [])
    .map((s) => s.id)
    .sort()
    .join(",");

  // Current signature of every source (points, base map and template are
  // observed here).
  const signatures = useLiveQuery(async () => {
    const ids = sourceIdsKey ? sourceIdsKey.split(",") : [];
    if (!ids.length) return {};
    const sources = await db.annotations.bulkGet(ids);
    const live = sources.filter(hasPathArray);
    const pointIds = live.flatMap((s) =>
      (s.points ?? []).map((p) => p?.id).filter(Boolean)
    );
    const baseMapIds = [
      ...new Set(live.map((s) => s.baseMapId).filter(Boolean)),
    ];
    const templateIds = [
      ...new Set(live.map((s) => s.pathArray.annotationTemplateId)),
    ];
    const [pointRows, baseMaps, templates] = await Promise.all([
      pointIds.length ? db.points.bulkGet(pointIds) : [],
      baseMapIds.length ? db.baseMaps.bulkGet(baseMapIds) : [],
      templateIds.length ? db.annotationTemplates.bulkGet(templateIds) : [],
    ]);
    const pointById = new Map(pointRows.filter(Boolean).map((p) => [p.id, p]));
    const baseMapById = new Map(baseMaps.filter(Boolean).map((b) => [b.id, b]));
    const templateById = new Map(
      templates.filter(Boolean).map((t) => [t.id, t])
    );
    const out = {};
    ids.forEach((id, i) => {
      const source = sources[i];
      out[id] = hasPathArray(source)
        ? getPathArraySignature({
            source,
            pointRows: (source.points ?? []).map((p) => pointById.get(p?.id)),
            baseMap: baseMapById.get(source.baseMapId),
            template: templateById.get(source.pathArray.annotationTemplateId),
          })
        : null;
    });
    return out;
  }, [sourceIdsKey]);

  // state

  const dataRef = useRef({ state: null, signatures: null, projectId: null });
  const timerRef = useRef(null);
  const runningRef = useRef(false);
  const rerunRef = useRef(false);
  const disposedRef = useRef(false);
  // sourceId → state already attempted WITHOUT success: never retried until
  // the source changes again.
  const failedRef = useRef(new Map());

  // helpers

  async function syncOnce() {
    const {
      state: current,
      signatures: sigs,
      projectId: pid,
    } = dataRef.current;
    if (!current || !sigs) return;
    const failed = failedRef.current;
    const sourceIds = new Set(current.sources.map((s) => s.id));

    // children whose source is gone / no longer carries a path array
    const orphanSourceIds = Object.keys(current.childCounts).filter(
      (id) => !sourceIds.has(id) && failed.get(id) !== "deleted"
    );
    if (orphanSourceIds.length) {
      orphanSourceIds.forEach((id) => failed.set(id, "deleted"));
      try {
        const deleted = await deletePathArrayChildrenService({
          sourceIds: orphanSourceIds,
          projectId: pid,
        });
        orphanSourceIds.forEach((id) => failed.delete(id));
        if (deleted) dispatch(triggerAnnotationsUpdate());
      } catch (error) {
        console.warn("[pathArraySync] removal skipped", error);
      }
    }

    for (const source of current.sources) {
      if (disposedRef.current) return;
      if (!(source.id in sigs)) continue;
      const signature = sigs[source.id];
      if (signature == null) continue;
      const count = current.childCounts[source.id] ?? 0;
      if (
        source.appliedSignature === signature &&
        source.appliedCount === count
      )
        continue;
      const attempt = `${signature}#${count}`;
      if (failed.get(source.id) === attempt) continue;
      failed.set(source.id, attempt);
      try {
        await applyPathArrayService({ sourceId: source.id, dispatch });
        failed.delete(source.id);
      } catch (error) {
        console.warn("[pathArraySync] regeneration skipped", source.id, error);
      }
    }
  }

  async function flush() {
    timerRef.current = null;
    if (runningRef.current) {
      rerunRef.current = true;
      return;
    }
    runningRef.current = true;
    try {
      do {
        rerunRef.current = false;
        await syncOnce();
      } while (rerunRef.current && !disposedRef.current);
    } finally {
      runningRef.current = false;
    }
  }

  // effects

  useEffect(() => {
    dataRef.current = {
      state: state ?? null,
      signatures: signatures ?? null,
      projectId,
    };
  }, [state, signatures, projectId]);

  // Scope switch: the ownership / read-only context changed — forget the
  // failures so the sources get another chance.
  useEffect(() => {
    failedRef.current.clear();
  }, [scopeId]);

  useEffect(() => {
    if (isReadOnly || !scopeId || !state || !signatures) return undefined;
    if (timerRef.current) clearTimeout(timerRef.current);
    timerRef.current = setTimeout(flush, DEBOUNCE_MS);
    return undefined;
  }, [state, signatures, isReadOnly, scopeId]);

  useEffect(() => {
    disposedRef.current = false;
    return () => {
      disposedRef.current = true;
      if (timerRef.current) clearTimeout(timerRef.current);
      timerRef.current = null;
    };
  }, []);
}
