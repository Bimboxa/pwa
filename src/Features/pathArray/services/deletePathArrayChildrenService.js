import db from "App/db/db";

import collectPathArrayChildren from "./collectPathArrayChildren";

// Rows to drop along with path array children: their own points (never
// shared, see applyPathArrayService — the holes `cuts` of the generated
// system rows included) and their template mapping relations.
export async function deletePathArrayChildRowsInTx(children) {
  if (!children?.length) return;
  const ids = children.map((c) => c.id);
  const pointIds = children
    .flatMap((c) => [
      ...(c.points ?? []),
      ...(c.cuts ?? []).flatMap((cut) => cut?.points ?? []),
    ])
    .map((p) => p?.id)
    .filter(Boolean);
  const relIds = (
    await db.relAnnotationMappingCategory
      .where("annotationId")
      .anyOf(ids)
      .toArray()
  )
    .filter((r) => !r.deletedAt)
    .map((r) => r.id);
  if (relIds.length) await db.relAnnotationMappingCategory.bulkDelete(relIds);
  if (pointIds.length) await db.points.bulkDelete(pointIds);
  await db.annotations.bulkDelete(ids);
}

// Removes every annotation generated by the path array (« Calepinage ») of
// the given sources — the source is gone or no longer carries a path array.
// A cascade recomputed from another row: no undo entry (tx.skipUndo).
// Returns the number of deleted children.
export default async function deletePathArrayChildrenService({
  sourceIds,
  projectId,
}) {
  const children = await collectPathArrayChildren({ sourceIds, projectId });
  if (!children.length) return 0;
  await db.transaction(
    "rw",
    db.annotations,
    db.points,
    db.relAnnotationMappingCategory,
    async (tx) => {
      tx.skipUndo = true;
      await deletePathArrayChildRowsInTx(children);
    }
  );
  return children.length;
}
