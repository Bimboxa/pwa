import { useSelector } from "react-redux";
import { useLiveQuery } from "dexie-react-hooks";

import {
  Box,
  Checkbox,
  ToggleButton,
  ToggleButtonGroup,
  Tooltip,
  Typography,
} from "@mui/material";

import WhiteSectionGeneric from "Features/form/components/WhiteSectionGeneric";
import AnnotationTemplateIcon from "Features/annotations/components/AnnotationTemplateIcon";

import db from "App/db/db";
import { resolveDrawingShape } from "Features/annotations/constants/drawingShapeConfig";

import {
  COMPONENT_ITEM_TYPE_POLYLINE,
  COMPONENT_ITEM_TYPE_STRIP,
} from "../constants/componentConstants";
import { getComponentItemType } from "../utils/getComponentItems";

// « Composant » field of a COMPONENT annotation template: the line templates
// of its listing the component generates — `template.componentItems =
// [{ annotationTemplateId, enabled, type }]` (see
// constants/componentConstants.js). Per template: included or not, drawn as a
// line or a band, generated by default or left unchecked in the drawing
// helper.
export default function FieldAnnotationTemplateComponentItems({
  value,
  onChange,
  annotationTemplateId,
  listingId: listingIdProp,
}) {
  // strings

  const titleS = "Composant";
  const helperS =
    "Une ligne dessinée avec ce modèle crée une annotation par modèle inclus.";
  const emptyS = "Aucun autre modèle de ligne dans cette liste";
  const defaultS = "Par défaut";
  const defaultTooltipS = "Coché par défaut au moment du dessin";
  const lineS = "Ligne";
  const stripS = "Bande";

  // data

  const selectedListingId = useSelector((s) => s.listings.selectedListingId);
  const listingId = listingIdProp ?? selectedListingId;
  const templates = useLiveQuery(async () => {
    if (!listingId) return [];
    const rows = await db.annotationTemplates
      .where("listingId")
      .equals(listingId)
      .toArray();
    return rows
      .filter(
        (t) =>
          !t.deletedAt &&
          t.id !== annotationTemplateId &&
          resolveDrawingShape(t) === "POLYLINE"
      )
      .sort((a, b) =>
        String(a.orderIndex ?? "") < String(b.orderIndex ?? "") ? -1 : 1
      );
  }, [listingId, annotationTemplateId]);

  // helpers

  const items = Array.isArray(value) ? value : [];
  const itemByTemplateId = new Map(
    items.map((item) => [item?.annotationTemplateId, item])
  );

  // handlers

  function handleToggleIncluded(template) {
    if (itemByTemplateId.has(template.id)) {
      onChange(items.filter((i) => i?.annotationTemplateId !== template.id));
      return;
    }
    onChange([
      ...items,
      {
        annotationTemplateId: template.id,
        enabled: true,
        type: getComponentItemType(null, template),
      },
    ]);
  }

  function handleItemChange(templateId, changes) {
    onChange(
      items.map((item) =>
        item?.annotationTemplateId === templateId
          ? { ...item, ...changes }
          : item
      )
    );
  }

  // render

  return (
    <WhiteSectionGeneric>
      <Box sx={{ display: "flex", flexDirection: "column", gap: 0.5 }}>
        <Typography variant="body2" sx={{ fontWeight: "bold" }}>
          {titleS}
        </Typography>
        <Typography variant="caption" color="text.secondary">
          {helperS}
        </Typography>
        {templates?.length === 0 && (
          <Typography variant="caption" color="text.secondary">
            {emptyS}
          </Typography>
        )}
        {(templates ?? []).map((template) => {
          const item = itemByTemplateId.get(template.id);
          const included = Boolean(item);
          return (
            <Box
              key={template.id}
              sx={{ display: "flex", alignItems: "center", gap: 0.5 }}
            >
              <Checkbox
                size="small"
                checked={included}
                onChange={() => handleToggleIncluded(template)}
                sx={{ p: 0.25 }}
              />
              <AnnotationTemplateIcon template={template} size={18} />
              <Typography variant="body2" noWrap sx={{ flex: 1, minWidth: 0 }}>
                {template.label}
              </Typography>
              {included && (
                <>
                  <ToggleButtonGroup
                    size="small"
                    exclusive
                    value={getComponentItemType(item, template)}
                    onChange={(_, type) =>
                      type && handleItemChange(template.id, { type })
                    }
                    sx={{
                      "& .MuiToggleButton-root": {
                        py: 0,
                        px: 0.75,
                        fontSize: 11,
                        textTransform: "none",
                      },
                    }}
                  >
                    <ToggleButton value={COMPONENT_ITEM_TYPE_POLYLINE}>
                      {lineS}
                    </ToggleButton>
                    <ToggleButton value={COMPONENT_ITEM_TYPE_STRIP}>
                      {stripS}
                    </ToggleButton>
                  </ToggleButtonGroup>
                  <Tooltip title={defaultTooltipS}>
                    <Box
                      component="label"
                      sx={{
                        display: "flex",
                        alignItems: "center",
                        cursor: "pointer",
                      }}
                    >
                      <Checkbox
                        size="small"
                        checked={item.enabled !== false}
                        onChange={(e) =>
                          handleItemChange(template.id, {
                            enabled: e.target.checked,
                          })
                        }
                        sx={{ p: 0.25 }}
                      />
                      <Typography variant="caption" color="text.secondary">
                        {defaultS}
                      </Typography>
                    </Box>
                  </Tooltip>
                </>
              )}
            </Box>
          );
        })}
      </Box>
    </WhiteSectionGeneric>
  );
}
