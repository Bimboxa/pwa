import db from "App/db/db";

import collectComponentChildren from "./collectComponentChildren";

// Rows to drop along with component children: their template mapping
// relations. NEVER their points — they are the points of the source.
export async function deleteComponentChildRowsInTx(children) {
  if (!children?.length) return;
  const ids = children.map((c) => c.id);
  const relIds = (
    await db.relAnnotationMappingCategory
      .where("annotationId")
      .anyOf(ids)
      .toArray()
  )
    .filter((r) => !r.deletedAt)
    .map((r) => r.id);
  if (relIds.length) await db.relAnnotationMappingCategory.bulkDelete(relIds);
  await db.annotations.bulkDelete(ids);
}

// Removes every annotation generated by the given component sources — the
// source is gone or is no longer a component. A cascade recomputed from
// another row: no undo entry (tx.skipUndo). Returns the number of deleted
// annotations.
export default async function deleteComponentChildrenService({
  sourceIds,
  projectId,
}) {
  const children = await collectComponentChildren({ sourceIds, projectId });
  if (!children.length) return 0;
  await db.transaction(
    "rw",
    db.annotations,
    db.relAnnotationMappingCategory,
    async (tx) => {
      tx.skipUndo = true;
      await deleteComponentChildRowsInTx(children);
    }
  );
  return children.length;
}
