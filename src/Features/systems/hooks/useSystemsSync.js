import { useEffect, useRef } from "react";

import { useDispatch, useSelector } from "react-redux";
import { useLiveQuery } from "dexie-react-hooks";

import { triggerAnnotationsUpdate } from "Features/annotations/annotationsSlice";

import db from "App/db/db";
import useReadOnlyScope from "Features/scopes/hooks/useReadOnlyScope";

import applySystemService, {
  getSystemProcedure,
} from "../services/applySystemService";
import deleteSystemChildrenService from "../services/deleteSystemChildrenService";
import { SYSTEM_ROLE_SOURCE } from "../constants/systemConstants";
import useSystemProcedures from "./useSystemProcedures";
import getSystemSignature from "../utils/getSystemSignature";

// Changes of the sources coalesce this long (a vertex drag = one pass).
const DEBOUNCE_MS = 400;

const isLive = (row) => Boolean(row) && !row.deletedAt;
const EMPTY = { sources: [], childCounts: {} };

/**
 * Keeps the annotations generated by the system instances (see
 * constants/systemConstants.js, applySystemService) in sync with their
 * source annotation, project-wide:
 *
 *   - source edited (vertices, closure, height, width, altitude), parameters
 *     edited, templates of the system listing or base map scale edited: the
 *     generated annotations are REGENERATED (reconciled in place);
 *   - a generated annotation is missing / in excess: same;
 *   - source deleted: the generated annotations are DELETED.
 *
 * A source = an annotation whose template is the SOURCE template of a system
 * listing — whatever path created it (2D / 3D drawing, paste, import).
 *
 * Same design as usePathArraySync: a watcher rather than a call at every
 * commit site, writes without undo entry (undoing the source change
 * re-derives the rows), the deletion of a source also cascading in
 * useDeleteAnnotations (same undo group). Skipped in read-only scopes; a
 * source whose regeneration fails is left alone until it changes again.
 */
export default function useSystemsSync() {
  // data

  const dispatch = useDispatch();
  const projectId = useSelector((s) => s.projects.selectedProjectId);
  const scopeId = useSelector((s) => s.scopes.selectedScopeId);
  const { isReadOnly } = useReadOnlyScope();
  const procedures = useSystemProcedures();
  const proceduresRef = useRef(procedures);
  proceduresRef.current = procedures;
  const proceduresKey = procedures
    .map((p) => `${p.key}@${p.version ?? 1}`)
    .join(",");

  // Sources of the project with their current signature, and the count of
  // generated annotations of every referenced source — live or not.
  const state = useLiveQuery(async () => {
    if (!projectId) return EMPTY;
    const listings = (
      await db.listings.where("projectId").equals(projectId).toArray()
    ).filter((l) => isLive(l) && l.system);

    const rows = await db.annotations
      .where("projectId")
      .equals(projectId)
      .toArray();
    const childCounts = {};
    for (const a of rows) {
      if (!isLive(a) || !a.systemSourceAnnotationId) continue;
      childCounts[a.systemSourceAnnotationId] =
        (childCounts[a.systemSourceAnnotationId] ?? 0) + 1;
    }
    if (!listings.length) return { sources: [], childCounts };

    const listingById = new Map(listings.map((l) => [l.id, l]));
    const templates = (
      await db.annotationTemplates
        .where("listingId")
        .anyOf([...listingById.keys()])
        .toArray()
    ).filter(isLive);
    const templatesByListingId = new Map();
    const sourceTemplateIds = new Set();
    for (const t of templates) {
      if (!templatesByListingId.has(t.listingId))
        templatesByListingId.set(t.listingId, []);
      templatesByListingId.get(t.listingId).push(t);
      if (t.systemRole === SYSTEM_ROLE_SOURCE) sourceTemplateIds.add(t.id);
    }

    const sourceRows = rows.filter(
      (a) =>
        isLive(a) &&
        !a.systemSourceAnnotationId &&
        sourceTemplateIds.has(a.annotationTemplateId) &&
        listingById.has(a.listingId)
    );
    if (!sourceRows.length) return { sources: [], childCounts };

    const pointIds = sourceRows.flatMap((s) =>
      (s.points ?? []).map((p) => p?.id).filter(Boolean)
    );
    const baseMapIds = [
      ...new Set(sourceRows.map((s) => s.baseMapId).filter(Boolean)),
    ];
    const [pointRows, baseMaps] = await Promise.all([
      pointIds.length ? db.points.bulkGet(pointIds) : [],
      baseMapIds.length ? db.baseMaps.bulkGet(baseMapIds) : [],
    ]);
    const pointById = new Map(pointRows.filter(Boolean).map((p) => [p.id, p]));
    const baseMapById = new Map(baseMaps.filter(Boolean).map((b) => [b.id, b]));

    const sources = sourceRows.map((source) => {
      const listing = listingById.get(source.listingId);
      return {
        id: source.id,
        appliedSignature: source.systemApplied?.signature ?? null,
        appliedCount: source.systemApplied?.count ?? null,
        signature: getSystemSignature({
          source,
          pointRows: (source.points ?? []).map((p) => pointById.get(p?.id)),
          baseMap: baseMapById.get(source.baseMapId),
          listing,
          templates: templatesByListingId.get(listing.id) ?? [],
          procedure: getSystemProcedure(listing, proceduresRef.current),
        }),
      };
    });
    return { sources, childCounts };
  }, [projectId, proceduresKey]);

  // state

  const dataRef = useRef({ state: null, projectId: null });
  const timerRef = useRef(null);
  const runningRef = useRef(false);
  const rerunRef = useRef(false);
  const disposedRef = useRef(false);
  // sourceId → state already attempted WITHOUT success: never retried until
  // the source changes again.
  const failedRef = useRef(new Map());

  // helpers

  async function syncOnce() {
    const { state: current, projectId: pid } = dataRef.current;
    if (!current) return;
    const failed = failedRef.current;
    const sourceIds = new Set(current.sources.map((s) => s.id));

    // generated annotations whose source is gone / no longer a system source
    const orphanSourceIds = Object.keys(current.childCounts).filter(
      (id) => !sourceIds.has(id) && failed.get(id) !== "deleted"
    );
    if (orphanSourceIds.length) {
      orphanSourceIds.forEach((id) => failed.set(id, "deleted"));
      try {
        const deleted = await deleteSystemChildrenService({
          sourceIds: orphanSourceIds,
          projectId: pid,
        });
        orphanSourceIds.forEach((id) => failed.delete(id));
        if (deleted) dispatch(triggerAnnotationsUpdate());
      } catch (error) {
        console.warn("[systemsSync] removal skipped", error);
      }
    }

    for (const source of current.sources) {
      if (disposedRef.current) return;
      if (source.signature == null) continue;
      const count = current.childCounts[source.id] ?? 0;
      if (
        source.appliedSignature === source.signature &&
        source.appliedCount === count
      )
        continue;
      const attempt = `${source.signature}#${count}`;
      if (failed.get(source.id) === attempt) continue;
      failed.set(source.id, attempt);
      try {
        await applySystemService({
          sourceId: source.id,
          procedures: proceduresRef.current,
          dispatch,
        });
        failed.delete(source.id);
      } catch (error) {
        console.warn("[systemsSync] regeneration skipped", source.id, error);
      }
    }
  }

  async function flush() {
    timerRef.current = null;
    if (runningRef.current) {
      rerunRef.current = true;
      return;
    }
    runningRef.current = true;
    try {
      do {
        rerunRef.current = false;
        await syncOnce();
      } while (rerunRef.current && !disposedRef.current);
    } finally {
      runningRef.current = false;
    }
  }

  // effects

  useEffect(() => {
    dataRef.current = { state: state ?? null, projectId };
  }, [state, projectId]);

  // Scope switch: the ownership / read-only context changed — forget the
  // failures so the sources get another chance.
  useEffect(() => {
    failedRef.current.clear();
  }, [scopeId]);

  useEffect(() => {
    if (isReadOnly || !scopeId || !state) return undefined;
    if (timerRef.current) clearTimeout(timerRef.current);
    timerRef.current = setTimeout(flush, DEBOUNCE_MS);
    return undefined;
  }, [state, isReadOnly, scopeId]);

  useEffect(() => {
    disposedRef.current = false;
    return () => {
      disposedRef.current = true;
      if (timerRef.current) clearTimeout(timerRef.current);
      timerRef.current = null;
    };
  }, []);
}
